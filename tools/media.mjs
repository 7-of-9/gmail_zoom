#!/usr/bin/env node
// Regenerates the live demo's copy of the extension and every image and video
// for the site and the Chrome Web Store, all from docs/demo/ (fake mail only):
//   docs/demo/ext/            content.js, content.css, version.js (copies)
//   docs/img/                 icon, screenshot-N.png (+ @2x.jpg), demo.mp4, demo-poster.jpg
//   store/img/                screenshot-1..4.png (1280x800), promo-440x280.png, marquee-1400x560.png
// Uses a private headless Chrome (tools/headless.mjs), never your own.
//   node tools/media.mjs              everything
//   node tools/media.mjs --no-video   skip the video
//   node tools/media.mjs --demo-only  only refresh docs/demo/ext/
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync, statSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { launch, sleep } from './headless.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const at = (...p) => join(ROOT, ...p);
const FFMPEG = process.env.FFMPEG || '/opt/homebrew/bin/ffmpeg';
const args = new Set(process.argv.slice(2));

// ---- 1. demo copy of the extension ----------------------------------------
mkdirSync(at('docs/demo/ext'), { recursive: true });
mkdirSync(at('docs/img'), { recursive: true });
mkdirSync(at('store/img'), { recursive: true });
copyFileSync(at('content.js'), at('docs/demo/ext/content.js'));
copyFileSync(at('content.css'), at('docs/demo/ext/content.css'));
const { version } = JSON.parse(readFileSync(at('manifest.json'), 'utf8'));
writeFileSync(at('docs/demo/ext/version.js'), `// generated by tools/media.mjs\nwindow.GPZ_VERSION = ${JSON.stringify(version)};\n`);
copyFileSync(at('icons/icon-128.png'), at('docs/img/icon-128.png'));
copyFileSync(at('icons/icon.svg'), at('docs/img/icon.svg'));
console.log(`demo: extension v${version} copied to docs/demo/ext/`);
if (args.has('--demo-only')) process.exit(0);

// ---- 2. captures of the demo ------------------------------------------------
const SENDER = {
  news: 'digest@weeklybyte.example.org',
  hub: 'notifications@codehub.example.com',
  sam: 'sam.rivera@northwind.example.com',
  fees: 'alex.morgan@fabrikam.example.com',
};
const preset = (def, levels) => JSON.stringify({ def, senders: Object.fromEntries(Object.entries(levels).map(([k, z]) => [SENDER[k], z])) });
const demoUrl = (q) => `file://${at('docs/demo/index.html')}?media&${new URLSearchParams(q)}`;
const tmp = mkdtempSync(join(tmpdir(), 'gpz-shots-'));
const chrome = await launch();

// Open the demo with these levels, optionally press keys / hover, capture.
async function capture(name, { open, def = 1, levels = {}, w = 1280, h = 800, scale = 2, keys = 0, hover = false, list }) {
  const p = await chrome.page(w, h, scale);
  await p.goto(demoUrl({ open, preset: preset(def, levels), ...(hover ? { video: 1 } : {}), ...(list ? { w: list } : {}) }), 1200);
  for (let i = 0; i < Math.abs(keys); i++) { await p.zoomKey(Math.sign(keys)); await sleep(120); }
  if (keys) await sleep(300);
  if (hover) {
    const r = await p.rect('#gpz-bar .gpz-pct');
    const x = r.x + r.w / 2, y = r.y + r.h / 2;
    await p.move(x, y);
    await p.eval(`demo.cursor(${x - 3}, ${y - 2})`);
    await sleep(300);
  }
  const pane = await p.rect('#pane');
  const pct = await p.eval(`document.querySelector('#gpz-bar .gpz-pct').textContent`);
  const file = join(tmp, `${name}.png`);
  await p.shot(file);
  await p.close();
  console.log(`capture ${name}: ${pct}`);
  return { src: `file://${file}`, pane, pct };
}

const LEVELS = { news: 1.5, hub: 1.1, sam: 1.3 };
const newsHover = await capture('news-hover', { open: 'news', levels: LEVELS, hover: true });
const news = await capture('news', { open: 'news', levels: LEVELS });
const hub = await capture('hub', { open: 'hub', levels: LEVELS });
const fees = await capture('fees', { open: 'fees', def: 1.6, levels: { ...LEVELS, fees: 1.6 }, keys: 1 });
const lap = await capture('laptop', { open: 'sam', levels: LEVELS });
const desk = await capture('desktop', { open: 'sam', levels: LEVELS, w: 1440, h: 900, list: 400 });

// ---- 3. store screenshots, promo tile, marquee -----------------------------
async function render(template, cfg, file, w, h, scale = 1) {
  const p = await chrome.page(w, h, scale);
  await p.goto(`file://${at('tools/media', template)}#${encodeURIComponent(JSON.stringify(cfg))}`, 900);
  await p.shot(file);
  await p.close();
}
const crop = (c) => [c.pane.x, c.pane.y, c.pane.w, c.pane.h];
const pairScale = (c) => 560 / c.pane.h;
const SHOTS = [
  { title: 'Zoom the email, not the whole of Gmail', sub: 'A small − % + control sits on the reading pane. Hover it for the shortcuts.',
    layout: 'single', panels: [{ src: newsHover.src }] },
  { title: 'Every sender keeps its own zoom', sub: 'Set it once: big for tiny-font newsletters, normal for notifications.',
    layout: 'pair', panels: [
      { src: news.src, crop: crop(news), scale: pairScale(news), label: `The Weekly Byte · <b>${news.pct}</b>` },
      { src: hub.src, crop: crop(hub), scale: pairScale(hub), label: `CodeHub · <b>${hub.pct}</b>` },
    ] },
  { title: 'Wide emails fit the pane', sub: '⌘⇧+ zooms in. Fixed-width Outlook tables and newsletters reflow instead of scrolling sideways.',
    layout: 'single', panels: [{ src: fees.src }] },
  { title: 'Same zoom on all your machines', sub: 'No login: your Gmail account is the identity, and your levels sync automatically.',
    layout: 'devices', syncText: 'same Gmail account', panels: [
      { src: lap.src, label: `Laptop · <b>${lap.pct}</b>` },
      { src: desk.src, label: `Desktop · <b>${desk.pct}</b>` },
    ] },
];
for (const [i, cfg] of SHOTS.entries()) {
  const n = i + 1;
  await render('screenshot.html', cfg, at(`store/img/screenshot-${n}.png`), 1280, 800, 1);
  copyFileSync(at(`store/img/screenshot-${n}.png`), at(`docs/img/screenshot-${n}.png`));
  const big = join(tmp, `screenshot-${n}@2x.png`);
  await render('screenshot.html', cfg, big, 1280, 800, 2);
  execFileSync('sips', ['-s', 'format', 'jpeg', '-s', 'formatOptions', '82', big, '--out', at(`docs/img/screenshot-${n}@2x.jpg`)], { stdio: 'ignore' });
  console.log(`screenshot ${n}: ${cfg.title}`);
}
await render('promo.html', {}, at('store/img/promo-440x280.png'), 440, 280, 1);
await render('marquee.html', { src: news.src }, at('store/img/marquee-1400x560.png'), 1400, 560, 1);
console.log('promo tile and marquee done');

// ---- 4. demo video ----------------------------------------------------------
// Each frame is a screenshot held for a set time (concat demuxer), so timing
// doesn't depend on how fast Chrome captures.
if (!args.has('--no-video')) {
  const frames = join(tmp, 'frames');
  mkdirSync(frames);
  const list = [];
  const p = await chrome.page(1280, 800, 1);
  await p.goto(demoUrl({ open: 'news', video: 1, preset: preset(1, { hub: 1.1, sam: 1.3 }) }), 1200);
  let cur = { x: 900, y: 520 };
  await p.eval(`demo.cursor(${cur.x}, ${cur.y})`);
  const snap = async (hold) => {
    const f = join(frames, `f${String(list.length).padStart(4, '0')}.png`);
    await p.shot(f);
    list.push([f, hold]);
  };
  const glide = async (x, y, steps = 9) => {
    const from = cur;
    for (let i = 1; i <= steps; i++) {
      const t = i / steps, e = t < 0.5 ? 2 * t * t : 1 - (-2 * t + 2) ** 2 / 2;
      await p.eval(`demo.cursor(${from.x + (x - from.x) * e}, ${from.y + (y - from.y) * e})`);
      await snap(0.035);
    }
    cur = { x, y };
  };
  const press = async (dir, hold) => { await p.zoomKey(dir); await sleep(260); await snap(hold); };
  const openRow = async (id) => {
    const r = await p.rect(`.row[data-open="${id}"]`);
    await glide(r.x + 150, r.y + r.h / 2);
    await p.click(cur.x, cur.y);
    await sleep(500);
  };

  await snap(1.4);                          // newsletter at 100%
  for (let i = 0; i < 4; i++) await press(1, 0.42);
  await press(1, 0.9);                      // 150%
  await sleep(1300); await snap(0.6);       // badge gone
  await openRow('hub'); await snap(1.6);    // its own 110%
  await openRow('news'); await snap(1.4);   // remembered 150%
  await openRow('fees'); await snap(0.8);   // unset: last level picked
  await press(1, 0.45);
  await press(1, 1.0);                      // 170%, wide table fits
  await sleep(1300); await snap(1.6);
  await p.close();

  const posterFrame = list.find(([f]) => f.endsWith('f0005.png')) || list[0];
  execFileSync('sips', ['-s', 'format', 'jpeg', '-s', 'formatOptions', '80', posterFrame[0], '--out', at('docs/img/demo-poster.jpg')], { stdio: 'ignore' });
  const concat = ['ffconcat version 1.0', ...list.flatMap(([f, d]) => [`file '${f}'`, `duration ${d}`]), `file '${list.at(-1)[0]}'`].join('\n');
  writeFileSync(join(tmp, 'frames.txt'), concat);
  execFileSync(FFMPEG, ['-y', '-loglevel', 'error', '-f', 'concat', '-safe', '0', '-i', join(tmp, 'frames.txt'),
    '-vf', 'fps=30,format=yuv420p', '-c:v', 'libx264', '-preset', 'slow', '-crf', '24', '-tune', 'stillimage',
    '-movflags', '+faststart', '-an', at('docs/img/demo.mp4')], { stdio: 'inherit' });
  const secs = list.reduce((s, [, d]) => s + d, 0);
  console.log(`video: ${list.length} frames, ${secs.toFixed(1)} s, ${(statSync(at('docs/img/demo.mp4')).size / 1e6).toFixed(2)} MB`);
}

await chrome.close();
rmSync(tmp, { recursive: true, force: true });
console.log('media done');
